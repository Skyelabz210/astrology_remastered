import * as Astronomy from 'astronomy-engine';
import { eclipsesBetween } from '../eclipses.js';
import { readFileSync, writeFileSync } from 'node:fs';
const from='1970-01-01T00:00:00.000Z',until='2031-01-01T00:00:00.000Z';
const result=eclipsesBetween(Astronomy,from,until);
if(result.truncated)throw new Error('Eclipse catalogue was truncated.');
const catalogue={source:'Astronomy Engine 2.1.19; geocentric model; generated reproducibly, not a separately observed catalogue',from,until,events:result.eclipses};
if(!Array.isArray(catalogue.events))throw new Error('Expected eclipse events.');
const output='// Generated by npm run eclipses:generate. Do not hand-edit.\nexport const ECLIPSE_CATALOGUE = '+JSON.stringify(catalogue,null,2)+';\nif(typeof window!=="undefined")window.EclipseCatalogue=ECLIPSE_CATALOGUE;\n';
const file=new URL('../src/astro/eclipse-catalogue.js',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(file,'utf8')!==output)throw new Error('Eclipse catalogue drift; run npm run eclipses:generate.');}
else writeFileSync(file,output);
process.stdout.write(`${catalogue.events.length} eclipse events, 1970–2030 inclusive.\n`);
