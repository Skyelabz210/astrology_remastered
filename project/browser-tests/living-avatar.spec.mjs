import { test, expect } from '@playwright/test';
test.beforeEach(async ({page})=>{await page.route('https://**/*',route=>route.abort());});
async function record(page) { return page.evaluate(()=>JSON.parse(localStorage.getItem('resonance.living-profile.v1')).profiles[0]); }
test('first onboarding run creates a living avatar that evolves through goals and counterexamples',async({page})=>{
  await page.goto('/resonance-spread.html');
  await page.getByRole('button',{name:/Cast the spread/i}).click();
  await expect(page.getByText(/Your avatar · Level 1 · 5 XP/)).toBeVisible();
  const first=await record(page);
  expect(first.baseline.computedAstrology.sections).toHaveLength(5);
  expect(first.observations).toHaveLength(0);
  await page.getByRole('button',{name:'Continue your avatar',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Behavioral profile',exact:true})).toBeVisible();
  await page.getByText('Your goals, preferences and cognitive habits',{exact:true}).click();
  await page.getByRole('button',{name:'Personalize your avatar',exact:true}).click();
  await page.getByLabel('What are you working toward?',{exact:true}).fill('Finish my design project');
  await page.getByLabel('How do you learn best?',{exact:true}).fill('Concrete examples and small experiments');
  await page.getByRole('button',{name:'Save my goals and preferences',exact:true}).click();
  await page.getByRole('combobox',{name:'Entry type',exact:true}).selectOption('reading-feedback');
  await page.getByRole('combobox',{name:'How did the reading fit?',exact:true}).selectOption('does-not-fit');
  await page.getByLabel('What happened? Include an example or a counterexample.',{exact:true}).fill('I found a counterexample: I slowed down before deciding.');
  await page.getByRole('button',{name:'Save check-in',exact:true}).click();
  await expect(page.locator('.living-xp strong')).toHaveText('10 XP');
  await expect(page.locator('#behavior-Sun .behavior-feedback')).toContainText('I found a counterexample');
  await expect(page.locator('#behavior-Sun .behavior-feedback')).toContainText('does not fit');
  await page.getByLabel('What happened? Include an example or a counterexample.',{exact:true}).fill('Another example from the same reading.');
  await page.getByRole('button',{name:'Save check-in',exact:true}).click();
  await expect(page.locator('.living-xp strong')).toHaveText('10 XP');
  const updated=await record(page);
  expect(updated.observations).toHaveLength(2);
  expect(updated.selfReported.preferences.learningStyle).toContain('small experiments');
  expect(updated.revision).toBeGreaterThan(first.revision);
  expect(updated.baseline.basisKey).toBe(first.baseline.basisKey);
  await page.reload();
  await page.getByRole('button',{name:/Cast the spread/i}).click();
  await page.getByRole('button',{name:'Continue your avatar',exact:true}).click();
  await expect(page.locator('.living-xp strong')).toHaveText('10 XP');
  await expect(page.locator('.living-avatar')).toContainText('Finish my design project');
  await page.screenshot({path:'test-results/living-avatar.png',fullPage:true});
});
test('changing a birth record creates a separate avatar without another user’s journal',async({page})=>{
  await page.goto('/resonance-spread.html');
  await page.getByRole('button',{name:/Cast the spread/i}).click();
  await page.getByRole('button',{name:'Continue your avatar',exact:true}).click();
  await page.getByLabel('What happened? Include an example or a counterexample.',{exact:true}).fill('First person private observation');
  await page.getByRole('button',{name:'Save check-in',exact:true}).click();
  await page.getByRole('button',{name:'Explore techniques',exact:true}).click();
  await page.getByRole('button',{name:'Your birth details',exact:true}).click();
  await page.getByLabel('Birth calendar',{exact:true}).fill('1993-06-10');
  await page.getByRole('button',{name:/Cast the spread/i}).click();
  await page.getByRole('button',{name:'Continue your avatar',exact:true}).click();
  await expect(page.locator('.living-avatar')).not.toContainText('First person private observation');
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('resonance.living-profile.v1')).profiles);
  expect(stored).toHaveLength(2);
  expect(stored.filter(p=>p.observations.length)).toHaveLength(1);
});
