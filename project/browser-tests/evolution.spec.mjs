import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync, strFromU8 } from 'fflate';
test.beforeEach(async({page})=>{await page.route('https://**/*',route=>route.abort());});
test('traditions and local keepsake are connected to the current avatar and offline archive',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/resonance-spread.html');
  await page.getByRole('button',{name:'Cast the spread',exact:true}).click();
  await page.getByRole('button',{name:'Continue your avatar',exact:true}).click();
  await page.locator('.evolution-panel').getByText('Jyotisha · nakshatras and Vimshottari',{exact:true}).click();
  await expect(page.getByRole('table',{name:'Admitted planetary nakshatras'})).toBeVisible();
  await expect(page.locator('.evolution-panel')).toContainText('Natal Moon:');
  await page.getByRole('combobox',{name:'Ayanamsha convention'}).selectOption('raman');
  await page.locator('.evolution-panel').getByText('Mayan calendar · Tzolk’in and Haab’',{exact:true}).click();
  await expect(page.locator('.evolution-panel')).toContainText('GMT 584283');
  const downloading=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download souvenir HTML',exact:true}).click();
  const souvenir=await downloading,html=await readFile(await souvenir.path(),'utf8');
  expect(html).toContain('Celestial souvenir');expect(html).toContain('Sun at');expect(html).not.toContain('<script');
  const zipping=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export all my data as ZIP',exact:true}).click();
  const zip=await zipping,files=unzipSync(await readFile(await zip.path()));
  expect(['report.html','souvenir.html','souvenir.md','souvenir.json','chart.svg','calculations.json'].every(p=>p in files)).toBe(true);
  expect(strFromU8(files['souvenir.html'])).toContain('Sun at');
  const saved=await page.evaluate(()=>window.ReadingRuns.loadRuns().find(r=>r.evidence.traditions));
  expect(saved.evidence.traditions.frame).toBe('raman');
  expect(errors).toEqual([]);
});
test('Mistral opt-in is reactive, key storage is explicit, and consultant rejects invented citations',async({page})=>{
  let calls=0;
  await page.route('https://api.mistral.ai/v1/chat/completions',async route=>{
    calls++;expect(route.request().headers().authorization).toBe('Bearer TEST_MISTRAL_KEY');
    const body=route.request().postDataJSON();expect(body.model).toBe('mistral-large-latest');
    expect(body.messages[0].content).not.toContain('PRIVATE_AVATAR_NOTE');
    await route.fulfill({json:{choices:[{message:{content:JSON.stringify({title:'Reflection',sections:[{title:'Anchor',text:'Your Sun in Libra can be a starting point for reflection.',citations:[calls===1?'invented:fact':'placement:Sun']}]})}}]}});
  });
  await page.goto('/resonance-spread.html');
  await page.getByRole('button',{name:'Cast the spread',exact:true}).click();
  await page.getByRole('button',{name:'Continue your avatar',exact:true}).click();
  await page.getByLabel('What happened? Include an example or a counterexample.',{exact:true}).fill('PRIVATE_AVATAR_NOTE');
  await page.getByRole('button',{name:'Save check-in',exact:true}).click();
  await page.getByText('Interpreter settings · OpenRouter',{exact:true}).click();
  await page.getByLabel('Mistral API key',{exact:true}).fill('TEST_MISTRAL_KEY');
  await page.getByRole('button',{name:'Use Mistral',exact:true}).click();
  expect(await page.evaluate(()=>localStorage.getItem('resonance.mistral.byok.v1'))).toBeNull();
  await page.getByRole('checkbox',{name:/Allow sending my birth record/}).check();
  await page.getByLabel('Ask your chart consultant',{exact:true}).fill('What can I reflect on?');
  await page.getByRole('button',{name:'Ask with source traces',exact:true}).click();
  await expect(page.locator('.evolution-generated')).toContainText('Your Sun in Libra can be a starting point for reflection.');
  expect(calls).toBe(2);
  await page.getByRole('button',{name:'Forget Mistral key',exact:true}).click();
  await expect(page.getByRole('button',{name:'Ask with source traces',exact:true})).toBeDisabled();
  await expect(page.locator('.evolution-generated')).toHaveCount(0);
});
