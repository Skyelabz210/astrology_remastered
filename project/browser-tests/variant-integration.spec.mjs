import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync, strFromU8 } from 'fflate';
test.beforeEach(async({page})=>{await page.route('https://**/*',route=>route.abort());});
async function navigate(page,id){
  await page.getByRole('button',{name:'Explore techniques',exact:true}).click();
  await page.locator(`[data-technique-id="${id}"]`).click();
  await expect(page.locator(`[data-technique-target="${id}"]`)).toBeFocused();
}
test('variant tools use admitted chart data, save distinct owned runs and export offline',async({page})=>{
  test.setTimeout(120000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:390,height:844});
  await page.goto('/resonance-spread.html');
  await navigate(page,'register-inspector');
  const lab=page.locator('.variant-lab');
  await expect(page.getByRole('table',{name:'Sun independent prime residues'})).toBeVisible();
  await page.getByLabel('Register body',{exact:true}).selectOption('Mercury');
  await expect(page.getByRole('table',{name:'Mercury independent prime residues'})).toBeVisible();
  await page.getByRole('button',{name:'Save inspected register',exact:true}).click();
  await expect(lab.locator('.variant-save-status')).toContainText('Calculation saved');
  await page.getByLabel('Signed integer',{exact:true}).fill('-35113');
  await page.getByLabel('Pairwise-coprime moduli',{exact:true}).fill('36,37');
  await page.getByRole('button',{name:'Decompose integer',exact:true}).click();
  await expect(lab.locator('.register-equation')).toContainText('Reconstructed exactly: yes');
  await page.getByLabel('Pairwise-coprime moduli',{exact:true}).fill('6,8');
  await page.getByRole('button',{name:'Decompose integer',exact:true}).click();
  await expect(lab).toContainText('Moduli must be at least 2 and pairwise coprime.');
  await navigate(page,'solar-arc');
  await expect(page.getByRole('table',{name:'Constructed solar-arc positions'})).toBeVisible();
  await page.getByRole('button',{name:'Save solar-arc calculation',exact:true}).click();
  await page.getByLabel('Solar-arc method',{exact:true}).selectOption('naibod');
  await page.getByRole('button',{name:'Save solar-arc calculation',exact:true}).click();
  await expect(page.locator('#behavior-Sun')).toContainText('Solar-arc reflection');
  await navigate(page,'stations');
  await page.getByLabel('Station search days',{exact:true}).fill('30');
  await page.getByRole('button',{name:'Search and save stations',exact:true}).click();
  await expect(page.getByRole('table',{name:'Located planetary stations'})).toBeVisible();
  await expect(lab.locator('.variant-save-status')).toContainText('Calculation saved');
  const runs=await page.evaluate(()=>window.ReadingRuns.loadRuns().filter(r=>['registerInspection','solarArc','stations'].includes(r.input.calculation?.kind)));
  expect(runs).toHaveLength(4);
  expect(new Set(runs.map(r=>r.profileKey)).size).toBe(1);
  expect(new Set(runs.map(r=>r.id)).size).toBe(4);
  expect(runs.find(r=>r.input.calculation.kind==='registerInspection').evidence.registerInspection.value.register.body).toBe('Mercury');
  expect(runs.filter(r=>r.input.calculation.kind==='solarArc').map(r=>r.evidence.solarArc.value.method).sort()).toEqual(['naibod','true']);
  expect(runs.every(r=>r.input.ephemeris==='Astronomy Engine 2.1.19')).toBe(true);
  const downloading=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export all my data as ZIP',exact:true}).click();
  const download=await downloading,files=unzipSync(await readFile(await download.path()));
  expect(strFromU8(files['data/personal-data.json'])).toContain('registerInspection');
  expect(strFromU8(files['data/personal-data.json'])).toContain('planetary-stations');
  expect(strFromU8(files['souvenir.json'])).toContain('solar-arc construction');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/variant-tools-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
});
test('composite is symmetric, retains both births and never supplies invented houses',async({page})=>{
  test.setTimeout(120000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/resonance-spread.html');
  await page.getByRole('button',{name:'Cast the spread',exact:true}).click();
  await page.getByRole('button',{name:'synastry',exact:true}).click();
  await page.getByPlaceholder('a name or initial',{exact:true}).fill('Composite partner');
  await page.getByLabel('Birth calendar',{exact:true}).fill('1990-01-01');
  await page.getByRole('button',{name:'Read the relationship',exact:true}).click();
  await navigate(page,'composite');
  await expect(page.getByRole('table',{name:'Short-arc relationship midpoints'})).toBeVisible();
  const run=await page.evaluate(()=>window.ReadingRuns.loadRuns().find(r=>r.input.kind==='synastry'));
  expect(run.input.partnerBirth.subjectName).toBe('Composite partner');
  const composite=run.evidence.composite.value;
  expect(composite.input.birthA.dateISO).toBe(run.input.birth.dateISO);
  expect(composite.input.birthB.dateISO).toBe(run.input.partnerBirth.dateISO);
  expect(composite.planets.every(p=>p.house===null&&p.speed===null)).toBe(true);
  const swapped=await page.evaluate(({birth,partner})=>window.VariantCalculations.compositeChart(window.computeNatal(partner),window.computeNatal(birth)).planets,{birth:run.input.birth,partner:run.input.partnerBirth});
  expect(composite.planets.map(p=>p.numerator)).toEqual(swapped.map(p=>p.numerator));
  const rejected=await page.evaluate(({context,arc})=>window.saveVariantCalculation({...context,profileKey:'foreign-owner'},'solarArc',{method:'true'},arc),{context:{at:run.at,input:run.input,profileKey:run.profileKey,evidence:run.evidence},arc:run.evidence.solarArc.value});
  expect(rejected).toBe(false);
  expect(errors).toEqual([]);
});
